定位本步目录 <- function() {
  参数 <- commandArgs(trailingOnly = FALSE)
  入口参数 <- grep("^--file=", 参数, value = TRUE)
  # source() 时优先使用最近一层的 ofile，兼容从别处调用和中文路径。
  来源 <- lapply(sys.frames(), function(环境) 环境$ofile)
  来源 <- Filter(function(x) is.character(x) && length(x) == 1L && nzchar(x), 来源)
  候选 <- if (length(来源)) tail(来源, 1L)[[1L]] else if (length(入口参数)) {
    sub("^--file=", "", tail(入口参数, 1L))
  } else character()
  if (length(候选) == 1L && file.exists(候选)) {
    return(dirname(normalizePath(候选, winslash = "/", mustWork = TRUE)))
  }
  stop(paste("无法可靠定位当前脚本。请在 RStudio 中手动 setwd() 到本步文件夹，",
             "再用 source(\"单步分析.R\", encoding=\"UTF-8\") 运行；不要逐行运行入口定位部分。"),
       call. = FALSE)
}

